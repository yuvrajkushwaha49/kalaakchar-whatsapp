/**
 * generate-ai-context.cjs
 * Cross-platform script to scan project repository structure and generate .ai/FILE_STRUCTURE.md
 * Uses only Node.js built-in modules.
 */

const fs = require('fs');
const path = require('path');

// Root of repository is current working directory or parent of scripts directory
const ROOT_DIR = path.resolve(__dirname, '..');
const OUTPUT_DIR = path.join(ROOT_DIR, '.ai');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'FILE_STRUCTURE.md');

// Directories and patterns to ignore during file tree generation
const IGNORED_NAMES = new Set([
  'node_modules',
  '.git',
  'dist',
  'build',
  'coverage',
  '.cache',
  '.system_generated',
  '.gemini',
  'brain',
  '.next',
  '.nuxt',
  'temp',
  'tmp',
  'package-lock.json',
  '.dev_store.json'
]);

function shouldIgnore(entryName) {
  if (IGNORED_NAMES.has(entryName)) return true;
  if (entryName.startsWith('.DS_Store') || entryName.endsWith('.log')) return true;
  return false;
}

function scanDirectory(dirPath, prefix = '') {
  let entries;
  try {
    entries = fs.readdirSync(dirPath, { withFileTypes: true });
  } catch (err) {
    return [`${prefix}[Error reading directory: ${err.message}]`];
  }

  // Sort directories first, then files alphabetically
  entries.sort((a, b) => {
    if (a.isDirectory() && !b.isDirectory()) return -1;
    if (!a.isDirectory() && b.isDirectory()) return 1;
    return a.name.localeCompare(b.name, undefined, { numeric: true, sensitivity: 'base' });
  });

  const lines = [];
  const visibleEntries = entries.filter(e => !shouldIgnore(e.name));

  visibleEntries.forEach((entry, idx) => {
    const isLast = idx === visibleEntries.length - 1;
    const connector = isLast ? '└── ' : '├── ';
    const childPrefix = prefix + (isLast ? '    ' : '│   ');

    if (entry.isDirectory()) {
      lines.push(`${prefix}${connector}${entry.name}/`);
      const subLines = scanDirectory(path.join(dirPath, entry.name), childPrefix);
      lines.push(...subLines);
    } else {
      lines.push(`${prefix}${connector}${entry.name}`);
    }
  });

  return lines;
}

function generateFileStructure() {
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const header = [
    '# Project File Structure',
    '',
    '> Automatically generated by `scripts/generate-ai-context.cjs`.',
    `> Last scanned: ${new Date().toISOString()}`,
    '',
    '```text',
    'campaignflow/'
  ];

  const treeLines = scanDirectory(ROOT_DIR, '  ');
  const footer = ['```', ''];

  const content = header.concat(treeLines, footer).join('\n');
  fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
  console.log(`✅ File structure generated successfully at: ${OUTPUT_FILE}`);
}

generateFileStructure();
